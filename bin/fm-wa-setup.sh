#!/usr/bin/env bash
# Arm or disarm the inbound WhatsApp check for this home.
#
# Usage:
#   fm-wa-setup.sh arm       write state/wa-watch.check.sh and register it
#   fm-wa-setup.sh disarm    remove the check and its registration
#   fm-wa-setup.sh status    report what is armed
#
# Arming writes the check shim into the home's gitignored state/ tree and binds
# it through the ordinary custom-check registration (bin/fm-check-register.sh),
# which is the same mechanism firstmate already uses for a task's merge poll.
# Nothing in fm-watch.sh, fm-watch-arm.sh, fm-wake-lib.sh or the away-mode
# daemon changes.
#
# It also writes config/wa-mode.env, the generated watcher cadence, exactly as
# fm-bootstrap.sh writes config/x-mode.env for Relay: without it the watcher
# sweeps every 300s, so a message the captain sends could wait five minutes for
# a wake. It exports the same FM_CHECK_INTERVAL=30 Relay uses, so a home running
# both cannot end up with two cadences that disagree.
#
# Opt-out has two levels, both clean:
#   - delete config/whatsapp.env: the poll becomes a hard no-op immediately and
#     the home reverts to no polling and no behaviour change
#   - run disarm: the check artifact, its registration, and the cadence file are
#     removed too, and the home stops counting as needing supervision
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"

# shellcheck source=bin/fm-wa-lib.sh
. "$SCRIPT_DIR/fm-wa-lib.sh"

CHECK_ID=wa-watch

usage() {
  echo "usage: fm-wa-setup.sh arm|disarm|status" >&2
}

paths() {
  fm_wa_paths
  CHECK="$FM_WA_STATE/$CHECK_ID.check.sh"
  TRUST="$FM_WA_STATE/$CHECK_ID.check-trust"
  CADENCE="$FM_WA_CONFIG_DIR/wa-mode.env"
}

# Byte-stable and generated, like Relay's own cadence file: it is sourced before
# a watcher process starts, never executed, and a home that never armed the
# channel has no such file and keeps the default cadence.
cadence_body() {
  cat <<'EOF'
# Auto-generated by bin/fm-wa-setup.sh - inbound WhatsApp watcher cadence.
# Source this before the active harness protocol starts a watcher process so
# fm-watch.sh sweeps the inbound check every 30s instead of every 300s. A home
# that has not armed the channel has no such file and keeps the default cadence.
# Remove it with 'fm-wa-setup.sh disarm'.
export FM_CHECK_INTERVAL=30
EOF
}

# The shim is deliberately trivial and byte-stable: it names this home and
# execs the repository's poll. The watcher snapshots and hashes it against the
# registration before running it, so any edit disarms it until re-registered.
shim_body() {
  # printf %q keeps a home or root path with spaces from splitting into
  # arguments, and the watcher runs this file through `bash <file>`, so no
  # execute bit is involved.
  cat <<EOF
#!/usr/bin/env bash
# Auto-generated by bin/fm-wa-setup.sh - inbound WhatsApp check shim.
# Registered with bin/fm-check-register.sh; edit it and the watcher will refuse
# to run it until you re-register. Remove it with 'fm-wa-setup.sh disarm'.
exec env FM_HOME=$(printf '%q' "$1") $(printf '%q' "$2/bin/fm-wa-poll.sh")
EOF
}

cmd_arm() {
  paths
  if ! fm_wa_load_config; then
    echo "error: nothing to arm; put FM_WA_CAPTAIN in ${FM_WA_CONFIG_FILE:-config/whatsapp.env} first" >&2
    return 1
  fi
  local home_abs root_abs
  home_abs=$(CDPATH='' cd -- "$FM_HOME" 2>/dev/null && pwd -P) \
    || { echo "error: cannot resolve this home" >&2; return 1; }
  root_abs=$(CDPATH='' cd -- "$FM_ROOT" 2>/dev/null && pwd -P) \
    || { echo "error: cannot resolve the firstmate root" >&2; return 1; }
  fm_wa_private_dir "$FM_WA_STATE" || { echo "error: state directory is unavailable" >&2; return 1; }
  shim_body "$home_abs" "$root_abs" | fm_wa_publish_stdin "$FM_WA_STATE" "$CHECK_ID.check.sh" \
    || { echo "error: cannot write the check shim" >&2; return 1; }
  chmod 700 -- "$CHECK" || { rm -f -- "$CHECK"; echo "error: cannot secure the check shim" >&2; return 1; }
  if ! FM_HOME="$FM_HOME" "$SCRIPT_DIR/fm-check-register.sh" "$CHECK_ID" >/dev/null; then
    rm -f -- "$CHECK" "$TRUST"
    echo "error: cannot register the check shim" >&2
    return 1
  fi
  # Written directly rather than through the state publisher: config/ holds this
  # home's other operating choices, so the cadence file is created at 0600
  # without reaching in and changing the directory it lands in.
  mkdir -p -- "$FM_WA_CONFIG_DIR" 2>/dev/null || true
  if ! ( umask 077; cadence_body > "$CADENCE.tmp" ) 2>/dev/null \
    || ! chmod 600 -- "$CADENCE.tmp" 2>/dev/null \
    || ! mv -f -- "$CADENCE.tmp" "$CADENCE" 2>/dev/null; then
    rm -f -- "$CADENCE.tmp" "$CHECK" "$TRUST" 2>/dev/null || true
    echo "error: cannot write the watcher cadence" >&2
    return 1
  fi
  echo "armed: state/$CHECK_ID.check.sh (inbound WhatsApp for $FM_WA_CAPTAIN)"
  echo "cadence: config/wa-mode.env (30s watcher sweep; source it before arming a watcher)"
  if ! fm_wa_paired; then
    echo "next: bin/fm-wa-listen.sh pair - the captain must enter the code on his phone"
  elif ! fm_wa_listener_pid >/dev/null 2>&1; then
    echo "next: bin/fm-wa-listen.sh start"
  fi
}

cmd_disarm() {
  paths
  local removed=0
  for artifact in "$CHECK" "$TRUST" "$CADENCE"; do
    if [ -e "$artifact" ] || [ -L "$artifact" ]; then
      rm -f -- "$artifact" && removed=1
    fi
  done
  if [ "$removed" -eq 1 ]; then
    echo "disarmed: removed the inbound WhatsApp check and its cadence; the listener is untouched"
    echo "stop the listener too with: bin/fm-wa-listen.sh stop"
  else
    echo "nothing armed"
  fi
}

cmd_status() {
  paths
  if fm_wa_load_config; then
    echo "config: on (captain $FM_WA_CAPTAIN)"
  else
    echo "config: off (${FM_WA_CONFIG_FILE:-config/whatsapp.env} has no FM_WA_CAPTAIN)"
  fi
  if [ -f "$CHECK" ]; then
    echo "check: present at state/$CHECK_ID.check.sh"
    [ -f "$TRUST" ] && echo "registration: present" || echo "registration: MISSING - re-run arm"
  else
    echo "check: absent (not armed)"
  fi
  if [ -f "$CADENCE" ]; then
    echo "cadence: present at config/wa-mode.env (30s watcher sweep)"
  else
    echo "cadence: absent (default watcher sweep)"
  fi
}

case "${1:-}" in
  arm) cmd_arm ;;
  disarm) cmd_disarm ;;
  status) cmd_status ;;
  ''|-h|--help|help) usage; [ -z "${1:-}" ] && exit 2 || exit 0 ;;
  *) usage; exit 2 ;;
esac
